"""Writes every logo file from one set of numbers (108-unit Android adaptive-icon grid; keep key inside the 66-unit safe circle).
Usage: python design/logo/make.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
BG, SIDE, FACE, ACCENT = "#26282D", "#A6A8AD", "#FFFFFF", "#33B5E5"
X0, Y0, W, H, FACE_H, R = 28, 26, 52, 54, 46, 10          # key box; corner circle stays ≤ 33 from centre
# mask drawn on a unit design, then scaled into the key face
MASK = ("M38.5,46.5 C42,43.8 47.5,43.6 51.2,45.8 L54,47.6 L56.8,45.8 C60.5,43.6 66,43.8 69.5,46.5 "
        "C69.6,53 66.2,57.6 61,57.6 C58.2,57.6 55.9,55.8 54,53.6 C52.1,55.8 49.8,57.6 47,57.6 "
        "C41.8,57.6 38.4,53 38.5,46.5 Z")
EYES = [(46.5, 50.6), (61.5, 50.6)]
S, CX, CY = 1.3, 54, 50.6                       # scale about the mask centre
TY = (Y0 + FACE_H / 2) - CY                      # centre the mask in the face

def tx(x): return round(CX + (x - CX) * S, 2)
def ty(y): return round(CY + (y - CY) * S + TY, 2)
def scale_path(d):
    out, xy = [], 0
    for tok in re.findall(r"[A-Za-z]|-?[\d.]+", d):
        if tok.isalpha(): out.append(tok); xy = 0; continue
        v = float(tok); out.append(str(tx(v) if xy % 2 == 0 else ty(v))); xy += 1
    return " ".join(out).replace(" ,", ",")
def ellipse(cx, cy):
    rx, ry = round(3.6 * S, 2), round(2.4 * S, 2)
    return f"M{tx(cx) - rx},{ty(cy)} a{rx},{ry} 0 1,0 {2*rx},0 a{rx},{ry} 0 1,0 {-2*rx},0 Z"
def rrect(x, y, w, h, r):
    return (f"M{x+r},{y} H{x+w-r} A{r},{r} 0 0 1 {x+w},{y+r} V{y+h-r} A{r},{r} 0 0 1 {x+w-r},{y+h} "
            f"H{x+r} A{r},{r} 0 0 1 {x},{y+h-r} V{y+r} A{r},{r} 0 0 1 {x+r},{y} Z")
mask = scale_path(MASK) + " " + " ".join(ellipse(*e) for e in EYES)
side, face = rrect(X0, Y0, W, H, R), rrect(X0, Y0, W, FACE_H, R)

def svg(body, note): return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">\n'
                             f'  <!-- Anon Keyboard: {note}. Generated by design/logo/make.py. -->\n{body}</svg>\n')
fg = (f'  <path fill="{SIDE}" d="{side}"/>\n  <path fill="{FACE}" d="{face}"/>\n'
      f'  <path fill="{ACCENT}" fill-rule="evenodd" d="{mask}"/>\n')
L = root / "design/logo"
(L / "anon-logo.svg").write_text(svg(f'  <rect width="108" height="108" rx="24" fill="{BG}"/>\n' + fg, "full logo"))
(L / "anon-foreground.svg").write_text(svg(fg, "adaptive foreground"))
(L / "anon-monochrome.svg").write_text(svg(f'  <path fill="#000" fill-rule="evenodd" d="{side} {mask}"/>\n', "themed-icon layer"))

def vec(paths, note):
    body = "".join(f'    <path android:fillColor="{c}"{" android:fillType=\"evenOdd\"" if eo else ""} android:pathData="{d}" />\n' for c, d, eo in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- {note}. Generated by design/logo/make.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'{body}</vector>\n')
D = root / "app/src/main/res/drawable"
(D / "ic_launcher_foreground.xml").write_text(vec([(SIDE, side, False), (FACE, face, False), (ACCENT, mask, True)], "Launcher icon foreground"))
(D / "ic_launcher_monochrome.xml").write_text(vec([("#FFFFFFFF", f"{side} {mask}", True)], "Themed icon (Android 13+), tinted by the system"))
colors = root / "app/src/main/res/values/strings.xml"
colors.write_text(re.sub(r'(<color name="ic_launcher_background">)[^<]*', rf"\g<1>{BG}", colors.read_text()))
print("written")
